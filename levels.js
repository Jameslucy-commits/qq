/* ───────── 辦公室與會議室關卡檔 ───────── */
levelAdd('office_with_meeting', function(K) {
  const { T, M, box, flat, desk, nodes, bounds, block, plate, screen } = K;

  // 1. 設定整體空間範圍（包含主辦公區與右側的會議空間）
  bounds(-12, 22, -12, 12);

  // 2. 設定障礙物（OA坐位、鐵櫃、會議桌、雜物堆），角色走路會自動避開
  block([
    // --- 主辦公區 ---
    [-8, -2, -6, 6],   
    [-1, 5, -6, 6],    
    [6, 12, -6, 6],    
    [-10, 10, -9, -7.5], 
    [-2, 0, 1, 3],     // 走道上的紙箱（溶漿）
    [3, 5, 2, 4],      // 走道上的紙箱（溶漿）

    // --- 會議空間 ---
    [14, 19, -5, 5],   // 中央大型會議桌
    [13, 21, -7, -6],  // 北側牆面雜物堆
    [13, 21, 6, 7],    // 南側牆面雜物堆
    [20, 21, -5, 5]    // 東側牆面雜物堆
  ]);

  // 3. 鋪上地板
  flat(34, 24, M.office, 5, 0, 0, 1);

  // 4. 主辦公區：鐵櫃與 12 個 OA 座位
  for(let x = -8; x <= 8; x += 3) {
    box(2.6, 1.0, 1.2, M.tool2, x, 0.5, -8.5); // 及腰辦公鐵櫃
  }
  
  const rows = [-4, -1, 2, 5];
  const cols = [-5, 2, 9];
  rows.forEach((z) => {
    cols.forEach((x) => {
      desk(x, z, 2.0); // 12個OA座位
    });
  });

  // 5. 入口與時鐘
  box(0.8, 0.8, 0.1, M.trim, 2, 3.5, -11.5); // 入口上方的大圓形時鐘

  // 6. 右側會議空間佈置
  box(0.4, 3.0, 8, M.wall, 12, 1.5, -8);   // 會議室西側牆（上半部）
  box(0.4, 3.0, 8, M.wall, 12, 1.5, 8);    // 會議室西側牆（下半部，留出門口走道）

  desk(16.5, 0, 3.5); // 中央大型會議桌

  // 角落冰箱與微波爐
  box(0.8, 1.6, 0.8, M.tool, 19, 0.8, -4.5); 
  box(0.5, 0.4, 0.5, M.tool2, 19, 1.2, -3.2); 

  // 移動式投影幕
  box(0.2, 1.8, 1.5, M.tool2, 13.5, 0.9, 0);

  // 四周物資箱與宣傳品
  for(let x = 14; x <= 20; x += 1.5) {
    box(1.2, 0.8, 1.0, M.desk, x, 0.4, -6.5); 
    box(1.2, 0.9, 1.0, M.desk, x, 0.45, 6.5);  
  }

  // 7. 設定角色走動的節點（Nodes）與路由
  nodes({
    "entrance": [9, 9],            
    "boss_seat": [-5, 5],          
    "meeting_room": [16, 0],       
    "pantry_corner": [19, -4.5]    
  }, "entrance-meeting_room meeting_room-pantry_corner meeting_room-boss_seat");
});
