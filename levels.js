levelAdd('office_with_meeting', function(K) {
  const { T, M, box, flat, desk, nodes, bounds, block, plate, screen } = K;

  // 1. 設定整體空間範圍（包含主辦公區與右側的會議空間）
  // X軸擴展到正右方以容納會議室
  bounds(-12, 22, -12, 12);

  // 2. 設定障礙物（OA坐位、鐵櫃、會議桌、雜物堆），角色走路會自動避開
  block([
    // --- 主辦公區 (X: -12 到 12) ---
    [-8, -2, -6, 6],   // 左排（靠牆，包含課長與股長）
    [-1, 5, -6, 6],    // 中排
    [6, 12, -6, 6],    // 右排
    [-10, 10, -9, -7.5], // 最前方辦公鐵櫃
    [-2, 0, 1, 3],     // 走道上的紙箱（溶漿）
    [3, 5, 2, 4],      // 走道上的紙箱（溶漿）

    // --- 會議空間 (X: 13 到 21) ---
    [14, 19, -5, 5],   // 中央大型會議桌
    // 四周圍堆放的物資、宣傳品與礦泉水箱雜物堆
    [13, 21, -7, -6],  // 北側牆面雜物堆
    [13, 21, 6, 7],    // 南側牆面雜物堆
    [20, 21, -5, 5]    // 東側（右側）牆面雜物堆
  ]);

  // 3. 鋪上地板
  flat(34, 24, M.office, 5, 0, 0, 1);

  // 4. 主辦公區：鐵櫃與 12 個 OA 座位
  for(let x = -8; x <= 8; x += 3) {
    box(2.6, 1.0, 1.2, M.tool2, x, 0.5, -8.5); // 及腰辦公鐵櫃
  }
  
  const rows = [-4, -1, 2, 5];
  const cols = [-5, 2, 9];
  rows.forEach((z) => {
    cols.forEach((x) => {
      desk(x, z, 2.0); // 12個OA座位
    });
  });

  // 5. 入口與時鐘
  box(0.8, 0.8, 0.1, M.trim, 2, 3.5, -11.5); // 入口上方的大圓形時鐘

  // 6. 右側會議空間佈置
  // (1) 隔間牆與門（在 X=12、Z 靠中間開門）
  box(0.4, 3.0, 8, M.wall, 12, 1.5, -8);   // 會議室西側牆（上半部）
  box(0.4, 3.0, 8, M.wall, 12, 1.5, 8);    // 會議室西側牆（下半部，中間留出門口走道 z: -2 至 2）

  // (2) 中央大型會議桌
  desk(16.5, 0, 3.5); 

  // (3) 角落的冰箱與微波爐（放置在會議室左上或左下角落，例如 X=19, Z=-4）
  box(0.8, 1.6, 0.8, M.tool, 19, 0.8, -4.5); // 冰箱
  box(0.5, 0.4, 0.5, M.tool2, 19, 1.2, -3.2); // 微波爐（疊在旁邊或檯面上）

  // (4) 移動式投影幕（放在會議桌前方或側邊，例如 X=14, Z=0）
  box(0.2, 1.8, 1.5, M.tool2, 13.5, 0.9, 0);

  // (5) 四周圍堆放的物資、礦泉水與宣傳品箱子
  // 用低矮的箱子方塊模擬堆疊的物資
  for(let x = 14; x <= 20; x += 1.5) {
    box(1.2, 0.8, 1.0, M.desk, x, 0.4, -6.5); // 北側物資箱
    box(1.2, 0.9, 1.0, M.desk, x, 0.45, 6.5);  // 南側宣傳品堆
  }

  // 7. 設定角色走動的節點（Nodes）與路由
  nodes({
    "entrance": [9, 9],            // 辦公區右上入口
    "boss_seat": [-5, 5],          // 課長座位
    "meeting_room": [16, 0],       // 會議室中央
    "pantry_corner": [19, -4.5]    // 會議室角落冰箱微波爐區
  }, "entrance-meeting_room meeting_room-pantry_corner meeting_room-boss_seat");
});

